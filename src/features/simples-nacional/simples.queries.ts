// The queries the upstream Simples Nacional repositories run (TipoDfeCalculoSimplesRepository,
// EnquadramentoRegimeSimplesRepository, TipoReceitaBrutaSimplesRepository,
// ClassificacaoTributariaSimplesRepository, AtividadeSimplesCalculoRepository,
// SituacaoIssParAliquotaSimplesRepository...), in SQLite for D1.
// Parameter ?1 is always the operation date. The NCM and NBS queries are the regular regime ones
// (calculation.queries.ts): the nomenclature services are the same class in both upstreams.

import { buildValidOnClause } from "@/shared/data/validity.period.ts";

const CBS_IBS_TAX_ID = 2;

function validOn(startColumn: string, endColumn: string) {
  const clause = buildValidOnClause({ startColumn, endColumn, dateParameter: "?1" });
  return clause;
}

const CBS_IBS_SITUATIONS = `
  SELECT TRIBUTO_SITUACAO_TRIBUTARIA.TRST_SITR_ID
  FROM TRIBUTO_SITUACAO_TRIBUTARIA
  WHERE TRIBUTO_SITUACAO_TRIBUTARIA.TRST_TBTO_ID = ${CBS_IBS_TAX_ID}`;

// why: a tpDoc without calculator treatment is refused before the Simples link is looked at; the
// newest link on the date gives the document's regime vocabulary, rate places, item cap and IS.
const SIMPLES_DOCUMENT_SQL = `
SELECT
  TIPO_DFE.TPDF_SIGLA AS acronym,
  TIPO_DFE.TPDF_B_PERMITE_NCM_ZERO AS allowsZeroNcm,
  TIPO_DFE.TPDF_B_POSSUI_TRATAMENTO_CALCULADORA AS hasCalculatorTreatment,
  SIMPLES_LINK.TDCS_ID IS NOT NULL AS isEnabled,
  SIMPLES_LINK.TDCS_VOCABULARIO_REGIME AS regimeVocabulary,
  SIMPLES_LINK.TDCS_CASAS_ALIQUOTA_CALCULO AS rateDecimalPlaces,
  SIMPLES_LINK.TDCS_MAXIMO_ITENS AS maxItems,
  SIMPLES_LINK.TDCS_IN_ADMITE_IS AS allowsSelectiveTax
FROM
  TIPO_DFE
LEFT JOIN
  TIPO_DFE_CALCULO_SIMPLES_NACIONAL AS SIMPLES_LINK ON SIMPLES_LINK.TDCS_ID = (
    SELECT TIPO_DFE_CALCULO_SIMPLES_NACIONAL.TDCS_ID
    FROM TIPO_DFE_CALCULO_SIMPLES_NACIONAL
    WHERE
      TIPO_DFE_CALCULO_SIMPLES_NACIONAL.TDCS_TPDF_ID = TIPO_DFE.TPDF_ID AND
      ${validOn("TIPO_DFE_CALCULO_SIMPLES_NACIONAL.TDCS_INICIO_VIGENCIA", "TIPO_DFE_CALCULO_SIMPLES_NACIONAL.TDCS_FIM_VIGENCIA")}
    ORDER BY TIPO_DFE_CALCULO_SIMPLES_NACIONAL.TDCS_INICIO_VIGENCIA DESC
    LIMIT 1
  )
WHERE
  TIPO_DFE.TPDF_TIPO = ?2 AND
  ${validOn("TIPO_DFE.TPDF_INICIO_VIGENCIA", "TIPO_DFE.TPDF_FIM_VIGENCIA")}
ORDER BY
  TIPO_DFE.TPDF_B_POSSUI_TRATAMENTO_CALCULADORA ASC
LIMIT 1;`;

// why: "IS ?n" matches a field not sent, as upstream's "(:x IS NULL AND x IS NULL) OR x = :x". CRT
// rows always have a CRT and NFS-e rows never do, so the vocabulary column tells them apart.
const SIMPLES_REGIME_SQL = `
SELECT
  ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL.ERSN_VOCABULARIO_REGIME AS vocabulary,
  REGIME_APURACAO_SIMPLES_NACIONAL.RASN_IN_CALCULA_TRIBUTOS AS calculatesTaxes,
  REGIME_APURACAO_SIMPLES_NACIONAL.RASN_IN_GERA_IBS AS generatesIbs,
  REGIME_APURACAO_SIMPLES_NACIONAL.RASN_DESTINO_DEVIDO AS dueDestination,
  REGIME_APURACAO_SIMPLES_NACIONAL.RASN_DESTINO_PENDENTE_SUSPENSO AS pendingDestination
FROM
  ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL
JOIN
  REGIME_APURACAO_SIMPLES_NACIONAL ON REGIME_APURACAO_SIMPLES_NACIONAL.RASN_ID = ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL.ERSN_RASN_ID
WHERE
  ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL.ERSN_CRT IS ?2 AND
  ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL.ERSN_TPREGIMEIBSCBS IS ?3 AND
  ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL.ERSN_OPSIMPNAC IS ?4 AND
  ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL.ERSN_REGAPIBSCBSSN IS ?5 AND
  ${validOn("ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL.ERSN_INICIO_VIGENCIA", "ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL.ERSN_FIM_VIGENCIA")} AND
  ${validOn("REGIME_APURACAO_SIMPLES_NACIONAL.RASN_INICIO_VIGENCIA", "REGIME_APURACAO_SIMPLES_NACIONAL.RASN_FIM_VIGENCIA")}
ORDER BY
  ENQUADRAMENTO_REGIME_SIMPLES_NACIONAL.ERSN_INICIO_VIGENCIA DESC,
  REGIME_APURACAO_SIMPLES_NACIONAL.RASN_INICIO_VIGENCIA DESC
LIMIT 1;`;

// why: the factors are REAL columns; as text they keep their digits for the exact decimals.
const GOVERNMENT_PURCHASE_FACTOR_SQL = `
SELECT
  CAST(TRANSICAO_ALIQUOTA_COMPRA_GOV_SIMPLES_NACIONAL.TACG_FATOR AS TEXT) AS factor
FROM
  TRANSICAO_ALIQUOTA_COMPRA_GOV_SIMPLES_NACIONAL
WHERE
  ${validOn("TRANSICAO_ALIQUOTA_COMPRA_GOV_SIMPLES_NACIONAL.TACG_INICIO_VIGENCIA", "TRANSICAO_ALIQUOTA_COMPRA_GOV_SIMPLES_NACIONAL.TACG_FIM_VIGENCIA")}
ORDER BY
  TRANSICAO_ALIQUOTA_COMPRA_GOV_SIMPLES_NACIONAL.TACG_INICIO_VIGENCIA DESC
LIMIT 1;`;

// why: the classic endpoint reads the default rows of each tpRBSN (no vocabulary); the NFS-e
// prefers its own rows (TRBS_VOCABULARIO_REGIME 'NFSE'), so both come back, newest first.
const REVENUE_TYPES_SQL = `
SELECT
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_VOCABULARIO_REGIME AS vocabulary,
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_CD AS code,
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_DESCRICAO AS description,
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_IN_COMPOE_RECEITA AS isRevenue,
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_IN_IS_COMPOE_RECEITA AS isSelectiveTaxRevenue,
  CAST(TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_FATOR_RECEITA AS TEXT) AS revenueFactor,
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_IN_PENDENTE_SUSPENSO AS isPending,
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_IN_EXIGE_ALIQUOTA AS requiresRates,
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_IN_VEDADO_NAO_TRIBUTAVEL AS refusesNonTaxableActivity
FROM
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL
WHERE
  ${validOn("TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_INICIO_VIGENCIA", "TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_FIM_VIGENCIA")}
ORDER BY
  TIPO_RECEITA_BRUTA_SIMPLES_NACIONAL.TRBS_INICIO_VIGENCIA DESC;`;

// why: SIPA_ORDEM is the order of the rate pair rules; within a rule the first matching row wins.
const ISS_SITUATIONS_SQL = `
SELECT
  SITUACAO_ISS_PAR_ALIQUOTA_SIMPLES_NACIONAL.SIPA_CAMPO AS field,
  SITUACAO_ISS_PAR_ALIQUOTA_SIMPLES_NACIONAL.SIPA_VALOR AS value,
  SITUACAO_ISS_PAR_ALIQUOTA_SIMPLES_NACIONAL.SIPA_REGRA AS rule,
  SITUACAO_ISS_PAR_ALIQUOTA_SIMPLES_NACIONAL.SIPA_TIPO_ALIQUOTA AS pairType
FROM
  SITUACAO_ISS_PAR_ALIQUOTA_SIMPLES_NACIONAL
WHERE
  ${validOn("SITUACAO_ISS_PAR_ALIQUOTA_SIMPLES_NACIONAL.SIPA_INICIO_VIGENCIA", "SITUACAO_ISS_PAR_ALIQUOTA_SIMPLES_NACIONAL.SIPA_FIM_VIGENCIA")}
ORDER BY
  SITUACAO_ISS_PAR_ALIQUOTA_SIMPLES_NACIONAL.SIPA_ORDEM ASC,
  SITUACAO_ISS_PAR_ALIQUOTA_SIMPLES_NACIONAL.SIPA_ID ASC;`;

const NOT_IMPLEMENTED_SQL = `
SELECT EXISTS (
  SELECT 1
  FROM
    TRATAMENTO_CLASSIFICACAO
  JOIN
    TRATAMENTO_TRIBUTARIO ON TRATAMENTO_TRIBUTARIO.TRTR_ID = TRATAMENTO_CLASSIFICACAO.TRCL_TRTR_ID
  JOIN
    CLASSIFICACAO_TRIBUTARIA ON CLASSIFICACAO_TRIBUTARIA.CLTR_ID = TRATAMENTO_CLASSIFICACAO.TRCL_CLTR_ID
  WHERE
    CLASSIFICACAO_TRIBUTARIA.CLTR_CD = ?2 AND
    TRATAMENTO_TRIBUTARIO.TRTR_IN_POSSUI_AJUSTE = 1 AND
    CLASSIFICACAO_TRIBUTARIA.CLTR_SITR_ID IN (${CBS_IBS_SITUATIONS}) AND
    ${validOn("CLASSIFICACAO_TRIBUTARIA.CLTR_INICIO_VIGENCIA", "CLASSIFICACAO_TRIBUTARIA.CLTR_FIM_VIGENCIA")} AND
    ${validOn("TRATAMENTO_CLASSIFICACAO.TRCL_INICIO_VIGENCIA", "TRATAMENTO_CLASSIFICACAO.TRCL_FIM_VIGENCIA")} AND
    ${validOn("TRATAMENTO_TRIBUTARIO.TRTR_INICIO_VIGENCIA", "TRATAMENTO_TRIBUTARIO.TRTR_FIM_VIGENCIA")}
) AS isFound;`;

// why: upstream checks the document link by code, with no validity on the classification itself.
const SIMPLES_CLASSIFICATION_SQL = `
SELECT
  CLASSIFICACAO_TRIBUTARIA.CLTR_TPRBSN AS revenueTypeCode,
  EXISTS (
    SELECT 1
    FROM
      TIPO_DFE_CLASSIFICACAO
    JOIN
      TIPO_DFE ON TIPO_DFE.TPDF_ID = TIPO_DFE_CLASSIFICACAO.TDCL_TPDF_ID
    JOIN
      CLASSIFICACAO_TRIBUTARIA AS LINKED_CLASSIFICATION ON LINKED_CLASSIFICATION.CLTR_ID = TIPO_DFE_CLASSIFICACAO.TDCL_CLTR_ID
    WHERE
      LINKED_CLASSIFICATION.CLTR_CD = ?2 AND
      TIPO_DFE.TPDF_TIPO = ?3 AND
      LINKED_CLASSIFICATION.CLTR_SITR_ID IN (${CBS_IBS_SITUATIONS}) AND
      ${validOn("TIPO_DFE_CLASSIFICACAO.TDCL_INICIO_VIGENCIA", "TIPO_DFE_CLASSIFICACAO.TDCL_FIM_VIGENCIA")} AND
      ${validOn("TIPO_DFE.TPDF_INICIO_VIGENCIA", "TIPO_DFE.TPDF_FIM_VIGENCIA")}
  ) AS isAllowedOnDocument
FROM
  CLASSIFICACAO_TRIBUTARIA
WHERE
  CLASSIFICACAO_TRIBUTARIA.CLTR_CD = ?2 AND
  CLASSIFICACAO_TRIBUTARIA.CLTR_SITR_ID IN (${CBS_IBS_SITUATIONS}) AND
  ${validOn("CLASSIFICACAO_TRIBUTARIA.CLTR_INICIO_VIGENCIA", "CLASSIFICACAO_TRIBUTARIA.CLTR_FIM_VIGENCIA")}
ORDER BY
  CLASSIFICACAO_TRIBUTARIA.CLTR_INICIO_VIGENCIA DESC
LIMIT 1;`;

const SIMPLES_ACTIVITY_SQL = `
SELECT
  ATIVIDADE_SIMPLES_NACIONAL.ATSN_CATIVSN AS code,
  ATIVIDADE_SIMPLES_NACIONAL.ATSN_IN_NAO_TRIBUTAVEL AS isNonTaxable,
  ATIVIDADE_SIMPLES_NACIONAL.ATSN_ANEXO_SEM_FATOR_R AS annexWithoutFatorR,
  ATIVIDADE_SIMPLES_NACIONAL.ATSN_ANEXO_COM_FATOR_R AS annexWithFatorR,
  ATIVIDADE_SIMPLES_NACIONAL.ATSN_IN_ISS_NO_SIMPLES AS hasIssInSimples,
  ATIVIDADE_SIMPLES_NACIONAL.ATSN_IN_ADMITE_BENEFICIO_MUNICIPAL AS allowsMunicipalBenefit,
  EXISTS (
    SELECT 1
    FROM
      TIPO_DFE_ATIVIDADE_SIMPLES_NACIONAL
    JOIN
      TIPO_DFE ON TIPO_DFE.TPDF_ID = TIPO_DFE_ATIVIDADE_SIMPLES_NACIONAL.TDAS_TPDF_ID
    WHERE
      TIPO_DFE_ATIVIDADE_SIMPLES_NACIONAL.TDAS_ATSN_ID = ATIVIDADE_SIMPLES_NACIONAL.ATSN_ID AND
      TIPO_DFE.TPDF_TIPO = ?3 AND
      ${validOn("TIPO_DFE_ATIVIDADE_SIMPLES_NACIONAL.TDAS_INICIO_VIGENCIA", "TIPO_DFE_ATIVIDADE_SIMPLES_NACIONAL.TDAS_FIM_VIGENCIA")} AND
      ${validOn("TIPO_DFE.TPDF_INICIO_VIGENCIA", "TIPO_DFE.TPDF_FIM_VIGENCIA")}
  ) AS isAllowedOnDocument
FROM
  ATIVIDADE_SIMPLES_NACIONAL
WHERE
  ATIVIDADE_SIMPLES_NACIONAL.ATSN_CATIVSN = ?2 AND
  ${validOn("ATIVIDADE_SIMPLES_NACIONAL.ATSN_INICIO_VIGENCIA", "ATIVIDADE_SIMPLES_NACIONAL.ATSN_FIM_VIGENCIA")}
ORDER BY
  ATIVIDADE_SIMPLES_NACIONAL.ATSN_INICIO_VIGENCIA DESC
LIMIT 1;`;


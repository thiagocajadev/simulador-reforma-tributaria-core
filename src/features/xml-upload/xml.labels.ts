function describeXmlTag(tag: string, numbering: string | null) {
  const groupLabel = GROUP_LABELS[tag];

  if (groupLabel && numbering) {
    const numbered = `${groupLabel} ${numbering}`;
    return numbered;
  }

  const label = groupLabel ?? FIELD_LABELS[tag] ?? null;
  return label;
}


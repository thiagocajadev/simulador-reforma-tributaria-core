// The Imposto Seletivo queries of one item, as ProcessamentoItemService.obterTratamentoClassificacao
// runs them for tribute 1: the IS CST (SituacaoTributariaRepository.existeCst), the IS classification
// with its treatment (ClassificacaoTributariaRepository.buscarClassificacaoTributaria,
// TratamentoClassificacaoRepository) and the rate rows of the NCM (selective.tax.match.ts).
// Parameter ?1 is the operation date; ?2 the IS CST, the IS cClassTrib or the full NCM.

import {
  buildAdRemMatchSql,
  buildAdValoremMatchSql,
  SELECTIVE_TAX_ID,
} from "@/shared/data/selective.tax.match.ts";
import { buildValidOnClause } from "@/shared/data/validity.period.ts";

function validOn(startColumn: string, endColumn: string) {
  const clause = buildValidOnClause({ startColumn, endColumn, dateParameter: "?1" });
  return clause;
}

const SELECTIVE_TAX_MATCH = { ncmExpression: "?2", dateParameter: "?1" };

const SELECTIVE_TAX_CST_SQL = `
SELECT EXISTS (
  SELECT 1
  FROM
    SITUACAO_TRIBUTARIA
  JOIN
    TRIBUTO_SITUACAO_TRIBUTARIA ON TRIBUTO_SITUACAO_TRIBUTARIA.TRST_SITR_ID = SITUACAO_TRIBUTARIA.SITR_ID
  WHERE
    SITUACAO_TRIBUTARIA.SITR_CD = ?2 AND
    TRIBUTO_SITUACAO_TRIBUTARIA.TRST_TBTO_ID = ${SELECTIVE_TAX_ID} AND
    ${validOn("TRIBUTO_SITUACAO_TRIBUTARIA.TRST_INICIO_VIGENCIA", "TRIBUTO_SITUACAO_TRIBUTARIA.TRST_FIM_VIGENCIA")} AND
    ${validOn("SITUACAO_TRIBUTARIA.SITR_INICIO_VIGENCIA", "SITUACAO_TRIBUTARIA.SITR_FIM_VIGENCIA")}
) AS isFound;`;

const SELECTIVE_TAX_CLASSIFICATION_SQL = `
SELECT
  SITUACAO_TRIBUTARIA.SITR_CD AS cstCode,
  TRATAMENTO_TRIBUTARIO.TRTR_DESCRICAO AS treatmentDescription,
  TRATAMENTO_TRIBUTARIO.TRTR_EXPRESSAO_BASE_CALCULO AS baseFormula,
  TRATAMENTO_TRIBUTARIO.TRTR_EXPRESSAO_TRIBUTO_CALCULADO AS calculatedTaxFormula,
  TRATAMENTO_TRIBUTARIO.TRTR_EXPRESSAO_TRIBUTO_DEVIDO AS taxDueFormula
FROM
  CLASSIFICACAO_TRIBUTARIA
JOIN
  SITUACAO_TRIBUTARIA ON SITUACAO_TRIBUTARIA.SITR_ID = CLASSIFICACAO_TRIBUTARIA.CLTR_SITR_ID
JOIN
  TRIBUTO_SITUACAO_TRIBUTARIA ON TRIBUTO_SITUACAO_TRIBUTARIA.TRST_SITR_ID = SITUACAO_TRIBUTARIA.SITR_ID
LEFT JOIN
  TRATAMENTO_CLASSIFICACAO ON
    TRATAMENTO_CLASSIFICACAO.TRCL_CLTR_ID = CLASSIFICACAO_TRIBUTARIA.CLTR_ID AND
    ${validOn("TRATAMENTO_CLASSIFICACAO.TRCL_INICIO_VIGENCIA", "TRATAMENTO_CLASSIFICACAO.TRCL_FIM_VIGENCIA")}
LEFT JOIN
  TRATAMENTO_TRIBUTARIO ON TRATAMENTO_TRIBUTARIO.TRTR_ID = TRATAMENTO_CLASSIFICACAO.TRCL_TRTR_ID
WHERE
  CLASSIFICACAO_TRIBUTARIA.CLTR_CD = ?2 AND
  TRIBUTO_SITUACAO_TRIBUTARIA.TRST_TBTO_ID = ${SELECTIVE_TAX_ID} AND
  ${validOn("CLASSIFICACAO_TRIBUTARIA.CLTR_INICIO_VIGENCIA", "CLASSIFICACAO_TRIBUTARIA.CLTR_FIM_VIGENCIA")} AND
  ${validOn("SITUACAO_TRIBUTARIA.SITR_INICIO_VIGENCIA", "SITUACAO_TRIBUTARIA.SITR_FIM_VIGENCIA")} AND
  ${validOn("TRIBUTO_SITUACAO_TRIBUTARIA.TRST_INICIO_VIGENCIA", "TRIBUTO_SITUACAO_TRIBUTARIA.TRST_FIM_VIGENCIA")}
LIMIT 1;`;

// why: a rate row with a NULL value still says the IS applies (existeIncidenciaImpostoSeletivo);
// every IS value is NULL at V0073, so today the rows only signal the incidence.
const SELECTIVE_TAX_RATES_SQL = `
SELECT
  (SELECT json_object('percent', ALIQUOTA_AD_VALOREM.AADV_VALOR) ${buildAdValoremMatchSql(SELECTIVE_TAX_MATCH)}) AS adValorem,
  (
    SELECT json_object('amount', ALIQUOTA_AD_REM.AARE_VALOR, 'unit', UNIDADE_MEDIDA.UNMD_SIGLA)
    ${buildAdRemMatchSql(SELECTIVE_TAX_MATCH)}
  ) AS adRem
WHERE
  EXISTS (SELECT 1 FROM NCM WHERE NCM.NCM_CD = ?2);`;

export { SELECTIVE_TAX_CLASSIFICATION_SQL, SELECTIVE_TAX_CST_SQL, SELECTIVE_TAX_RATES_SQL };
